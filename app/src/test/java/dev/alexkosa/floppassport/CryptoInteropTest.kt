package dev.alexkosa.floppassport

import dev.alexkosa.floppassport.crypto.Base58
import dev.alexkosa.floppassport.crypto.DidKey
import dev.alexkosa.floppassport.crypto.Ed25519
import dev.alexkosa.floppassport.crypto.PassportDerivation
import dev.alexkosa.floppassport.technocore.Canonical
import org.junit.Assert.assertArrayEquals
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNotEquals
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * Release-blocking interoperability with Technocore.
 *
 * Every expected value comes from ReferenceVectors, which was generated by running the
 * server's own didkey.py and clean_text sweep. If these fail, the app would produce
 * writes the live server refuses, and no amount of UI polish matters.
 */
class CryptoInteropTest {

    private fun hex(s: String) = ByteArray(s.length / 2) {
        ((Character.digit(s[it * 2], 16) shl 4) or Character.digit(s[it * 2 + 1], 16)).toByte()
    }

    @Test
    fun `derives the same public key and DID as the server`() {
        for (id in ReferenceVectors.identities) {
            val seed = hex(id.seedHex)
            val pub = Ed25519.publicKeyFromSeed(seed)
            assertArrayEquals("public key for seed ${id.seedHex}", hex(id.publicKeyHex), pub)
            assertEquals("did for seed ${id.seedHex}", id.did, DidKey.fromPublicKey(pub))
        }
    }

    @Test
    fun `parses a DID back to the same key bytes`() {
        for (id in ReferenceVectors.identities) {
            assertArrayEquals(hex(id.publicKeyHex), DidKey.publicKey(id.did))
            assertTrue(DidKey.isDid(id.did))
        }
    }

    @Test
    fun `computes the identity fingerprint and note path the server looks up`() {
        for (id in ReferenceVectors.identities) {
            assertEquals(id.fingerprint, DidKey.fingerprint(id.did))
            assertEquals(id.notePath, DidKey.notePath(id.did))
        }
    }

    @Test
    fun `single-line sweep matches the server character for character`() {
        for (case in ReferenceVectors.sweeps) {
            assertEquals(
                "sweep of ${case.input.map { it.code.toString(16) }}",
                case.swept,
                Canonical.sweep(case.input),
            )
        }
    }

    @Test
    fun `builds the exact canonical payload the signature must cover`() {
        for (m in ReferenceVectors.messages) {
            assertEquals(
                m.canonicalPayload,
                Canonical.messagePayload(m.room, m.nonce, m.rawText),
            )
        }
    }

    @Test
    fun `produces byte-identical signatures to the server's signer`() {
        val seed = hex(ReferenceVectors.identities[0].seedHex)
        for (m in ReferenceVectors.messages) {
            val sig = Ed25519.sign(seed, m.canonicalPayload.toByteArray(Charsets.UTF_8))
            assertEquals("signature for ${m.canonicalPayload}", m.signature, Ed25519.encodeSignature(sig))
            assertTrue("canonical spelling", Canonical.isCanonicalSignature(m.signature))
        }
    }

    @Test
    fun `signs notes the way the server verifies them`() {
        val seed = hex(ReferenceVectors.identities[0].seedHex)
        for (n in ReferenceVectors.notes) {
            val payload = Canonical.notePayload(n.room, n.nonce.let { _ -> n.canonicalPayload.split("|")[1] }, n.nonce, n.rawText)
            assertEquals(n.canonicalPayload, payload)
            assertEquals(n.signature, Ed25519.encodeSignature(Ed25519.sign(seed, payload.toByteArray(Charsets.UTF_8))))
        }
    }

    @Test
    fun `verifies a good signature and rejects a tampered payload`() {
        val id = ReferenceVectors.identities[0]
        val m = ReferenceVectors.messages[0]
        val pub = DidKey.publicKey(id.did)
        val sig = Ed25519.decodeSignature(m.signature)
        assertTrue(Ed25519.verify(pub, m.canonicalPayload.toByteArray(Charsets.UTF_8), sig))
        assertFalse(
            "a changed message must not verify",
            Ed25519.verify(pub, (m.canonicalPayload + " ").toByteArray(Charsets.UTF_8), sig),
        )
        assertFalse(
            "another key must not verify",
            Ed25519.verify(DidKey.publicKey(ReferenceVectors.identities[1].did), m.canonicalPayload.toByteArray(Charsets.UTF_8), sig),
        )
    }

    @Test
    fun `signing raw text instead of swept text is what a broken client does`() {
        // Guards the single most likely integration bug: the server stores and verifies
        // the swept text, so a client that signs what the user typed gets a 403 that
        // looks like a key problem.
        val raw = "  swept  text  with\ttabs  "
        assertNotEquals(
            Canonical.messagePayload("lobby", "1", raw),
            "lobby|1|$raw",
        )
    }

    @Test
    fun `nonce and signature shapes match the server's regexes`() {
        assertTrue(Canonical.isValidNonce("1"))
        assertTrue(Canonical.isValidNonce("1756500000000"))
        assertFalse("20 digits exceeds int64", Canonical.isValidNonce("12345678901234567890"))
        assertFalse(Canonical.isValidNonce(""))
        assertFalse(Canonical.isValidNonce("12a"))
        // 86 base64url characters carry 516 bits for a 512-bit signature, so the last
        // character has four bits nothing reads. Only [AQgw] end in four zero bits;
        // every other spelling decodes to the same signature but the server refuses it.
        assertTrue(Canonical.isCanonicalSignature("A".repeat(85) + "Q"))
        assertFalse("last character must end in four zero bits",
            Canonical.isCanonicalSignature("A".repeat(85) + "B"))
        assertFalse("wrong length", Canonical.isCanonicalSignature("A".repeat(85)))
        assertFalse("base64 padding is not base64url",
            Canonical.isCanonicalSignature("A".repeat(84) + "=="))
    }

    @Test
    fun `base58 round-trips including leading zero bytes`() {
        val cases = listOf(
            ByteArray(32),
            ByteArray(32) { 0xFF.toByte() },
            hex(ReferenceVectors.identities[0].publicKeyHex),
        )
        for (c in cases) assertArrayEquals(c, Base58.decode(Base58.encode(c)))
    }

    @Test
    fun `a Solana address maps onto a did-key with no key material in between`() {
        val pub = hex(ReferenceVectors.identities[0].publicKeyHex)
        val solanaAddress = Base58.encode(pub)
        assertEquals(ReferenceVectors.identities[0].did, DidKey.fromSolanaAddress(solanaAddress))
    }

    @Test
    fun `passport derivation is deterministic and wallet-bound`() {
        val walletA = "So11111111111111111111111111111111111111112"
        val walletB = "11111111111111111111111111111111"
        val sig = ByteArray(64) { (it * 7).toByte() }

        val seed1 = PassportDerivation.seedFromWalletSignature(sig, walletA)
        val seed2 = PassportDerivation.seedFromWalletSignature(sig, walletA)
        assertArrayEquals("same wallet, same signature must rebuild the same Passport", seed1, seed2)

        val other = PassportDerivation.seedFromWalletSignature(sig, walletB)
        assertFalse("a different wallet must not land on the same identity", seed1.contentEquals(other))

        val changed = PassportDerivation.seedFromWalletSignature(ByteArray(64) { 1 }, walletA)
        assertFalse(seed1.contentEquals(changed))
        assertEquals(32, seed1.size)
    }

    @Test
    fun `the derivation statement is stable and says what it is`() {
        val s = PassportDerivation.statement("So11111111111111111111111111111111111111112")
        assertTrue(s.contains("FLOP Passport key derivation v1"))
        assertTrue("the user must be told it moves no funds", s.contains("moves no funds"))
        assertTrue(s.contains("So11111111111111111111111111111111111111112"))
    }

    @Test
    fun `the derivation statement is pinned byte for byte`() {
        // One changed byte here is a different key for every user. `contains` checks
        // above would let a stray space or a reworded line through; this one does not.
        val expected = "FLOP Passport key derivation v1\n" +
            "\n" +
            "Signing this creates your FLOP Passport identity.\n" +
            "It is not a transaction and moves no funds.\n" +
            "\n" +
            "wallet: So11111111111111111111111111111111111111112\n" +
            "app: dev.alexkosa.floppassport\n"
        assertEquals(expected, PassportDerivation.statement("So11111111111111111111111111111111111111112"))
        assertEquals(
            "FLOP Passport for Seeker. First signed check-in. 2543c207ef95a95a",
            dev.alexkosa.floppassport.ui.checkInText("did:key:z6Mkq2w8fJHnRES8sLV8ZC9YeiRG2eBJnLsqbvhyvg3zU1qs"),
        )
    }
}
