"""Turn tests/reference-vectors.json into a dependency-free Kotlin fixture file.

Emitting source rather than parsing JSON at test time keeps the unit tests pure JVM with
no extra dependency, and makes every invisible character in a fixture visible as an
escape in the diff -- which is the whole point of these cases.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

BS = chr(92)

SAFE = set(
    "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789"
    " !#%&'()*+,-./:;<=>?@[]^_{|}~"
)


def kstr(s: str) -> str:
    out = [chr(34)]
    for ch in s:
        if ch in SAFE:
            out.append(ch)
        elif ch == chr(34):
            out.append(BS + chr(34))
        elif ch == BS:
            out.append(BS + BS)
        elif ch == chr(36):
            out.append(BS + chr(36))
        else:
            hexed = ch.encode('utf-16-be', 'surrogatepass').hex()
            for i in range(0, len(hexed), 4):
                out.append(BS + 'u' + hexed[i:i + 4])
    out.append(chr(34))
    return "".join(out)


v = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))
L = []
w = L.append
w("package dev.alexkosa.flooppassport")
w("")
w("/**")
w(" * GENERATED by tools/emit_kotlin_fixtures.py -- do not edit by hand.")
w(" *")
w(" * Every value here was produced and then verified by Technocore's own")
w(" * `src/didkey.py` and `store.clean_text`, so a failure in these tests means our")
w(" * client disagrees with the server that will actually judge our writes.")
w(" */")
w("object ReferenceVectors {")
w("")
w("    data class Identity(")
w("        val seedHex: String,")
w("        val publicKeyHex: String,")
w("        val did: String,")
w("        val fingerprint: String,")
w("        val notePath: String,")
w("    )")
w("")
w("    data class Sweep(val input: String, val swept: String)")
w("")
w("    data class Signed(")
w("        val did: String,")
w("        val canonicalPayload: String,")
w("        val signature: String,")
w("        val room: String,")
w("        val nonce: String,")
w("        val rawText: String,")
w("    )")
w("")
w("    val identities = listOf(")
for i in v["identities"]:
    w(f'        Identity({kstr(i["seed_hex"])}, {kstr(i["public_key_hex"])}, {kstr(i["did"])}, {kstr(i["fingerprint"])}, {kstr(i["note_path"])}),')
w("    )")
w("")
w("    val sweeps = listOf(")
for s in v["sweep"]:
    w(f'        Sweep({kstr(s["input"])}, {kstr(s["swept"])}),')
w("    )")
w("")
w("    val messages = listOf(")
for m in v["messages"]:
    w(f'        Signed({kstr(m["did"])}, {kstr(m["canonical_payload"])}, {kstr(m["signature"])}, {kstr(m["room"])}, {kstr(m["nonce"])}, {kstr(m["raw_text"])}),')
w("    )")
w("")
w("    val notes = listOf(")
for n in v["notes"]:
    w(f'        Signed({kstr(n["did"])}, {kstr(n["canonical_payload"])}, {kstr(n["signature"])}, {kstr(n["ns"])}, {kstr(n["nonce"])}, {kstr(n["raw_value"])}),')
w("    )")
w("}")

out = Path(sys.argv[2])
out.write_text("\n".join(L) + "\n", encoding="utf-8")
print("wrote", out, "-", len(L), "lines")
